#!/usr/bin/env python3
"""
build.py - the one command that rebuilds every number, THESIS.md and the dashboard.

    python build.py                       # from the pinned tables in data/ (no keys, no internet)
    python build.py --check               # only verify the pinned tables against data/MANIFEST.json
    python build.py --test                # rebuild, then run the test suite
    python build.py --refresh market      # re-fetch price/supply/peers/DefiLlama first (internet)
    python build.py --refresh wallet      # re-read the buyback wallet balance history (internet, slow)
    python build.py --refresh bq          # re-run every BigQuery query (Google sign-in + BQ_PROJECT)
    python build.py --refresh swaps       # re-summarise + re-audit the raw swap file (needs data/intents_swaps.jsonl)
    python build.py --refresh market wallet bq swaps   # everything

Steps:  1 verify pinned tables  ->  2 (optional) refresh sources and re-pin  ->
        3 data/derived/metrics.json (measured metrics, HSP-029 sensitivity, lead-lag, thesis.yaml scorecard)  ->
        4 THESIS.md from docs/THESIS.template.md  ->  5 dashboard/index.html
Standard library only. Python 3.8+.
"""

import argparse
import hashlib
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, "data")
MANIFEST = os.path.join(DATA, "MANIFEST.json")
PINNED_DIRS = ["summary", "audit", "bq", "onchain", "market"]
PINNED_FILES = ["summary.json"]
sys.path.insert(0, os.path.join(ROOT, "pipeline"))
sys.path.insert(0, os.path.join(ROOT, "dashboard"))


def pinned_files():
    out = [os.path.join(DATA, f) for f in PINNED_FILES if os.path.exists(os.path.join(DATA, f))]
    for d in PINNED_DIRS:
        base = os.path.join(DATA, d)
        if os.path.isdir(base):
            out += [os.path.join(base, f) for f in sorted(os.listdir(base)) if os.path.isfile(os.path.join(base, f))]
    return sorted(out)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def rel(p):
    return os.path.relpath(p, ROOT).replace("\\", "/")


def write_manifest():
    files = {rel(p): sha256(p) for p in pinned_files()}
    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump({"note": "SHA-256 of every pinned input table. build.py refuses to build if one changes unexpectedly.",
                   "files": files}, f, indent=2, sort_keys=True)
    print("  pinned %d tables in data/MANIFEST.json" % len(files))


def verify():
    if not os.path.exists(MANIFEST):
        print("  no data/MANIFEST.json yet - creating it from the current tables")
        write_manifest()
        return True
    with open(MANIFEST, encoding="utf-8") as f:
        want = json.load(f)["files"]
    bad = []
    for path, digest in want.items():
        full = os.path.join(ROOT, path)
        if not os.path.exists(full):
            bad.append("missing  " + path)
        elif sha256(full) != digest:
            bad.append("changed  " + path)
    extra = [rel(p) for p in pinned_files() if rel(p) not in want]
    for b in bad:
        print("  " + b)
    for e in extra:
        print("  not pinned (ignored): " + e)
    if bad:
        print("  -> %d pinned table(s) differ from data/MANIFEST.json. If you refreshed on purpose, run with --repin." % len(bad))
        return False
    print("  all %d pinned tables match data/MANIFEST.json" % len(want))
    return True


def run(cmd):
    print("  $ " + " ".join(cmd))
    r = subprocess.run([sys.executable] + cmd, cwd=ROOT)
    if r.returncode != 0:
        sys.exit("Step failed: %s" % " ".join(cmd))


def refresh(sources):
    if "swaps" in sources:
        if not os.path.exists(os.path.join(DATA, "intents_swaps.jsonl")):
            sys.exit("--refresh swaps needs data/intents_swaps.jsonl (download it with pipeline/download_swaps.py; needs a JWT).")
        run(["pipeline/summarize_swaps.py", "--input", "data/intents_swaps.jsonl", "--out", "data"])
        run(["pipeline/audit_swaps.py"])
        print("  note: data/audit/gap_check.csv is only refreshed by  python pipeline/check_gaps.py  (needs the JWT)")
    if "market" in sources:
        run(["pipeline/fetch_market.py"])
    if "wallet" in sources:
        run(["pipeline/buyback_wallet.py", "--start", "2026-03-18", "--step-days", "7"])
    if "bq" in sources:
        run(["pipeline/bq_run.py", "all"])


def render_thesis():
    from build_dashboard import fill
    from render import render_thesis as tables
    tpl = os.path.join(ROOT, "docs", "THESIS.template.md")
    with open(os.path.join(DATA, "derived", "metrics.json"), encoding="utf-8") as f:
        met = json.load(f)["metrics"]
    with open(tpl, encoding="utf-8") as f:
        text = tables(fill(f.read(), met), met)  # numbers first, then the generated tables
    head = ("<!-- GENERATED by build.py from docs/THESIS.template.md and data/derived/metrics.json. "
            "Edit the template, not this file. -->\n")
    with open(os.path.join(ROOT, "THESIS.md"), "w", encoding="utf-8") as f:
        f.write(head + text)
    print("  THESIS.md written (every number filled from metrics.json)")


def main():
    ap = argparse.ArgumentParser(description="Rebuild every number, THESIS.md and the dashboard.")
    ap.add_argument("--refresh", nargs="*", choices=["market", "wallet", "bq", "swaps"], default=[],
                    help="re-fetch these sources before building (then re-pin)")
    ap.add_argument("--check", action="store_true", help="only verify pinned tables")
    ap.add_argument("--repin", action="store_true", help="accept the current tables and rewrite data/MANIFEST.json")
    ap.add_argument("--test", action="store_true", help="run the test suite after building")
    args = ap.parse_args()

    print("1) Pinned tables")
    if args.refresh:
        print("2) Refreshing: " + ", ".join(args.refresh))
        refresh(args.refresh)
        write_manifest()
    elif args.repin:
        write_manifest()
    elif not verify():
        sys.exit(1)
    if args.check:
        return

    import metrics
    import build_dashboard
    print("3) Metrics")
    doc = metrics.run(DATA)
    if doc["not_computed"]:
        print("  some metrics could not be computed - see 'not_computed' in data/derived/metrics.json")
    print("4) THESIS.md")
    render_thesis()
    print("5) Dashboard")
    build_dashboard.build(DATA, os.path.join(ROOT, "dashboard", "index.html"))
    print("\nDone. Open dashboard/index.html in a browser, and read THESIS.md.")
    if args.test:
        print("\n6) Tests")
        r = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"], cwd=ROOT)
        sys.exit(r.returncode)


if __name__ == "__main__":
    main()
